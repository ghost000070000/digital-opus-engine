// Assembles the editor script from its modules. No dependencies.
//
//   node build/build-editor.js          write editor/src/01-editor.js
//   node build/build-editor.js --check  fail if 01-editor.js is stale
//
// editor/src/modules/NN-name.js are the source of truth, concatenated in
// filename order (strict contiguous NN numbering, like engine/src). The output
// keeps its historical path because the editor page, Editable/Playable
// exports, the site builders and the tests all read editor/src/01-editor.js.
// Never edit 01-editor.js directly; edit the module and rebuild.
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const MODULES_DIR = path.join(ROOT, 'editor', 'src', 'modules');
const OUTPUT = path.join(ROOT, 'editor', 'src', '01-editor.js');
const HEADER = '// GENERATED by build/build-editor.js from editor/src/modules/*.js -- edit those files, not this one.\n';

function assembleEditor() {
  const files = fs.readdirSync(MODULES_DIR).filter((f) => f.endsWith('.js')).sort();
  if (!files.length) throw new Error(`No editor modules in ${path.relative(ROOT, MODULES_DIR)}`);
  files.forEach((file, index) => {
    const expected = String(index + 1).padStart(2, '0') + '-';
    if (!file.startsWith(expected) || !/^\d{2}-[a-z0-9-]+\.js$/.test(file)) {
      throw new Error(`Editor modules must be numbered contiguously as NN-kebab-name.js: expected ${expected}*, found ${file}`);
    }
  });
  return HEADER + files.map((file) => {
    const body = fs.readFileSync(path.join(MODULES_DIR, file), 'utf8');
    if (!body.endsWith('\n')) throw new Error(`${file} must end with a newline`);
    return body;
  }).join('');
}

// Unchanged output is not rewritten. Rewriting an existing file in place
// intermittently fails on Windows (errno -4094), so write then rename.
function buildEditor({ check = false } = {}) {
  const contents = assembleEditor();
  let current = null;
  try { current = fs.readFileSync(OUTPUT, 'utf8'); } catch (error) { if (error.code !== 'ENOENT') throw error; }
  if (current === contents) return { changed: false };
  if (check) throw new Error('editor/src/01-editor.js is stale or hand-edited: edit editor/src/modules/* and run node build/build-editor.js');
  fs.writeFileSync(OUTPUT + '.tmp', contents, 'utf8');
  fs.renameSync(OUTPUT + '.tmp', OUTPUT);
  return { changed: true };
}

module.exports = { assembleEditor, buildEditor };

if (require.main === module) {
  const check = process.argv.includes('--check');
  const result = buildEditor({ check });
  console.log(check ? 'Editor script fresh' : `Editor script -> editor/src/01-editor.js (${result.changed ? 'written' : 'unchanged'})`);
}
